/**
 * Election Campaign OS — the site's component classes exist
 *
 * This guard exists because of a specific bug, and the bug is the
 * argument for it.
 *
 * The advertising consent banner gave its "No adverts" button
 * `site-btn-outline`. There is no such class — the stylesheet defines
 * `site-btn-outline-ink` and `site-btn-outline-paper` — so the refusal
 * rendered as bare text beside a filled gold "Allow adverts" button.
 * That is the dark pattern the component's own header says it is not,
 * and it shipped through a green test suite, a clean typecheck, the hex
 * guard and the type-scale guard, because an undefined CSS class is
 * silent everywhere. It was caught by looking at the rendered page.
 *
 * Tailwind's `@apply` component classes are the one part of this
 * styling system with no compile-time check at all. A misspelt
 * `text-body-md` would be caught by `check:type-scale` and a raw hex by
 * `check:hex`; a misspelt `site-btn-*` is caught by nothing. Now it is
 * caught here.
 *
 * Proved by injection: changing `site-btn-outline-paper` back to
 * `site-btn-outline` in ConsentBanner.tsx fails "every site- component
 * class used is defined". Reverted clean.
 */
import { readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';

const SITE = path.resolve(__dirname);
const CSS = readFileSync(path.join(SITE, 'site.css'), 'utf-8');

/**
 * The component-layer prefixes — the ones defined by `@apply` in
 * site.css rather than generated by Tailwind from the theme.
 *
 * Deliberately NOT every `site-` class. `text-site-h3`, `font-site-display`
 * and friends are theme utilities Tailwind generates from
 * `tailwind.config.js`, and `check:type-scale` already governs them.
 * Mixing the two would make this guard fail on correct code, and a
 * guard that fails on correct code gets switched off.
 */
const COMPONENT_PREFIXES = ['site-btn', 'site-field', 'site-card'];

/** Every `.site-…` rule the stylesheet actually defines. */
const DEFINED = new Set(
  [...CSS.matchAll(/^\s*\.([a-z0-9-]+)\s*\{/gm)].map((m) => m[1]),
);

function tsxFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...tsxFiles(full));
    else if (entry.endsWith('.tsx')) out.push(full);
  }
  return out;
}

/** Blanked, not deleted, so reported line numbers stay honest. */
function stripComments(source: string): string {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '))
    .replace(/\/\/[^\n]*/g, (m) => m.replace(/[^\n]/g, ' '));
}

describe('the site stylesheet', () => {
  it('defines the component classes it is expected to', () => {
    // A sanity check on the extraction itself: if this regex stopped
    // matching, every assertion below would pass vacuously.
    for (const known of ['site-btn-primary', 'site-btn-outline-ink', 'site-btn-outline-paper']) {
      expect(DEFINED.has(known), `site.css should define .${known}`).toBe(true);
    }
  });

  it('every site- component class used is defined', () => {
    const offenders: string[] = [];

    for (const file of tsxFiles(SITE)) {
      const body = stripComments(readFileSync(file, 'utf-8'));
      const used = new Set(
        [...body.matchAll(/\b(site-[a-z0-9-]+)\b/g)].map((m) => m[1]),
      );

      for (const cls of used) {
        if (!COMPONENT_PREFIXES.some((p) => cls.startsWith(p))) continue;
        if (DEFINED.has(cls)) continue;
        offenders.push(`${path.relative(SITE, file)} uses .${cls}, which site.css does not define`);
      }
    }

    expect(offenders).toEqual([]);
  });

  it('the consent banner styles refusal and acceptance at equal weight', () => {
    /**
     * The specific regression. Both controls must carry a real button
     * class — one filled, one outlined — so neither reads as the lesser
     * option. Consent that is not freely given is not consent.
     */
    const banner = stripComments(
      readFileSync(path.join(SITE, 'ads', 'ConsentBanner.tsx'), 'utf-8'),
    );

    expect(banner).toContain('site-btn-primary');
    expect(banner).toContain('site-btn-outline-paper');
    // And neither may be a bare link or an unstyled button.
    expect(banner).not.toMatch(/className="site-btn-outline"/);
  });
});
